import { describe, it, expect } from "vitest";
import { maskSensitive, maskDeep } from "../lib/privacy/mask";

describe("maskSensitive — 양성 (마스킹)", () => {
  it.each([
    ["900101-1234567", "하이픈"],
    ["900101 1234567", "공백"],
    ["9001011234567", "구분자 없음"],
    ["010203-3123456", "2000년대생"],
    ["850315-5123456", "외국인등록번호"],
    ["000229-4123456", "윤년 2월 29일"],
    ["8801151000138", "구분자 없음 + 주민번호 체크섬 유효 (EAN 체크섬도 통과하지만 마스킹)"],
  ])("주민번호 %s (%s)", (rrn) => {
    expect(maskSensitive(`번호는 ${rrn}입니다`)).toBe("번호는 [주민번호]입니다");
  });

  it.each([
    ["4111111111111111", "Visa 연속"],
    ["4111-1111-1111-1111", "Visa 하이픈"],
    ["5555 5555 5555 4444", "MasterCard 공백"],
    ["2223003122003222", "MasterCard 2-series"],
    ["378282246310005", "Amex 15자리"],
    ["3782 822463 10005", "Amex 4-6-5"],
    ["6011111111111117", "Discover"],
    ["9410111111111118", "9 시작"],
  ])("카드번호 %s (%s)", (card) => {
    expect(maskSensitive(`카드 ${card} 결제`)).toBe("카드 [카드번호] 결제");
  });
});

describe("maskSensitive — 음성 (보존)", () => {
  it.each([
    ["010-1234-5678", "휴대전화"],
    ["02-123-4567", "유선전화"],
    ["01012345678", "휴대전화 붙여쓰기"],
    ["포스기 비밀번호 4829", "PIN 4자리"],
    ["도어락 00000000", "비밀번호 8자리"],
    ["사업자번호 123-45-67890", "사업자등록번호"],
    ["1234567890", "사업자번호 붙여쓰기"],
    ["110-123-456789", "계좌 12자리"],
    ["1002-345-678901", "계좌 13자리 하이픈"],
    ["3333-01-1234567", "계좌 13자리 4-2-7"],
    ["1234567890123", "계좌 13자리 연속"],
    ["79791234567890", "계좌 14자리 연속"],
    ["12345678901237", "계좌 14자리 (Luhn 통과)"],
    ["8801234567893", "EAN-13 바코드"],
    ["8809876543213", "EAN-13 바코드"],
    ["4006381333931", "EAN-13 바코드"],
    ["4000123456789", "13자리 일련번호 (Luhn 실패)"],
    ["일련번호 5733CO", "모델 일련번호"],
    ["1,250,000원", "금액"],
    ["89000원", "금액 붙여쓰기"],
    ["[12:34] 설명", "타임스탬프"],
    ["01:02:03", "타임스탬프 hh:mm:ss"],
    ["4111111111111112", "16자리 Luhn 실패"],
    ["1234567890123452", "16자리 Luhn 통과 but 1 시작"],
    ["2000000000000006", "2 시작 but MasterCard 범위 밖"],
    ["901301-1234567", "주민번호 형식 but 13월"],
    ["900101-9234567", "7번째 자리 9"],
  ])("%s (%s)", (text) => {
    expect(maskSensitive(text)).toBe(text);
  });
});

describe("maskDeep", () => {
  it("문자열 값만 마스킹하고 숫자·구조는 유지", () => {
    const doc = {
      overview: { summary: "주민번호 900101-1234567 확인", sourceTimestamp: { start: 1, end: 2 } },
      equipment: [{ name: "포스기", notes: "비밀번호 4829" }],
    };
    expect(maskDeep(doc)).toEqual({
      overview: { summary: "주민번호 [주민번호] 확인", sourceTimestamp: { start: 1, end: 2 } },
      equipment: [{ name: "포스기", notes: "비밀번호 4829" }],
    });
  });
});
